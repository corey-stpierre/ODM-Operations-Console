<#
QuestODM-Remove-CollectionsFromCsv.ps1

Removes collections listed in a CSV generated by QuestODM-Export-AllCollections.ps1

Expected CSV columns:
- CollectionName
- CollectionId   (preferred if present)
- ObjectCount    (optional)
- Description    (optional)

Behavior:
- DRY-RUN by default
- Use -Execute to actually remove collections
- Exports a report of what would be / was removed

Requirements:
- Windows PowerShell 5.1
- OdmApi module
#>

[CmdletBinding(SupportsShouldProcess = $true)]
param(
  [Parameter(Mandatory)]
  [ValidateSet("US","EU","AU","CA","UK","us","eu","au","ca","uk")]
  [string]$Region,

  [Parameter(Mandatory)]
  [string]$OrganizationId,

  [Parameter(Mandatory)]
  [string]$ProjectId,

  [Parameter(Mandatory)]
  [string]$AccountsProjectWorkloadId,

  [Parameter(Mandatory)]
  [string]$CsvPath,

  [switch]$Execute,

  [string]$OutDir = "C:\Temp\ODM_Reports"
)

function Normalize-Name {
  param([string]$s)
  if ([string]::IsNullOrWhiteSpace($s)) { return $null }
  return $s.Trim()
}

if ($PSVersionTable.PSVersion.Major -ne 5) {
  throw "Run this in Windows PowerShell 5.1."
}

if (-not (Test-Path $CsvPath)) {
  throw "CSV not found: $CsvPath"
}

if (-not (Test-Path $OutDir)) {
  New-Item -Path $OutDir -ItemType Directory -Force | Out-Null
}

$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$reportPath = Join-Path $OutDir "RemoveCollections_Report_$stamp.csv"

Connect-OdmService -Region $Region.ToLower() | Out-Null
Select-OdmOrganization -OrganizationId $OrganizationId | Out-Null

$proj = Get-OdmProject | Where-Object { $_.Id -eq $ProjectId }
if (-not $proj) {
  throw "Project with Id '$ProjectId' not found."
}

Select-OdmProjectWorkload -ProjectWorkloadId $AccountsProjectWorkloadId | Out-Null

$rows = Import-Csv -Path $CsvPath
if (-not $rows) {
  throw "CSV is empty or unreadable: $CsvPath"
}

$headers = $rows[0].PSObject.Properties.Name
if (-not ($headers -contains "CollectionName")) {
  throw "CSV must contain at least the CollectionName column."
}

$collections = @()
try {
  $collections = Get-OdmCollection -All
}
catch {
  $collections = Get-OdmCollection
}

if (-not $collections) {
  throw "No collections returned in current workload context."
}

$byId = @{}
$byName = @{}

foreach ($c in $collections) {
  if ($c.Id -and -not $byId.ContainsKey([string]$c.Id)) {
    $byId[[string]$c.Id] = $c
  }
  if ($c.Name -and -not $byName.ContainsKey($c.Name)) {
    $byName[$c.Name] = $c
  }
}

$report = New-Object System.Collections.Generic.List[object]

foreach ($row in $rows) {
  $csvName = Normalize-Name $row.CollectionName
  $csvId = $null
  if ($row.PSObject.Properties.Name -contains "CollectionId") {
    if ($row.CollectionId) { $csvId = [string]$row.CollectionId }
  }

  if (-not $csvName -and -not $csvId) {
    continue
  }

  $coll = $null

  if ($csvId -and $byId.ContainsKey($csvId)) {
    $coll = $byId[$csvId]
  }
  elseif ($csvName -and $byName.ContainsKey($csvName)) {
    $coll = $byName[$csvName]
  }

  if (-not $coll) {
    $report.Add([pscustomobject]@{
      CollectionName = $csvName
      CollectionId   = $csvId
      Status         = "FAILED"
      Details        = "Collection not found in current workload context"
    }) | Out-Null
    continue
  }

  $action = "Remove collection '$($coll.Name)'"

  if (-not $Execute) {
    Write-Host "[DRYRUN] $action"
    $report.Add([pscustomobject]@{
      CollectionName = $coll.Name
      CollectionId   = $coll.Id
      Status         = "DRYRUN"
      Details        = "Would remove collection"
    }) | Out-Null
    continue
  }

  try {
    if ($PSCmdlet.ShouldProcess($coll.Name, $action)) {
      Remove-OdmCollection -Collection $coll -Confirm:$false
    }

    $report.Add([pscustomobject]@{
      CollectionName = $coll.Name
      CollectionId   = $coll.Id
      Status         = "REMOVED"
      Details        = "Collection removed"
    }) | Out-Null
  }
  catch {
    $report.Add([pscustomobject]@{
      CollectionName = $coll.Name
      CollectionId   = $coll.Id
      Status         = "FAILED"
      Details        = $_.Exception.Message
    }) | Out-Null
  }
}

$report | Sort-Object CollectionName | Export-Csv -NoTypeInformation -Encoding UTF8 -Path $reportPath

Write-Host ""
Write-Host "Report exported: $reportPath" -ForegroundColor Green
if (-not $Execute) {
  Write-Host "No changes made. Re-run with -Execute to remove collections." -ForegroundColor Cyan
}